/**
 * ITEM-19/27: keep the agent instruction files in each project location on
 * the stable bootstrap of the active workspace.
 *
 * Targets are the artifacts of the configured tools plus every instruction
 * file already present that Letra generated (recognized by its header), even
 * when no tool is configured. A present instruction file without the Letra
 * header is human-authored: it is reported as a conflict and never touched.
 * Regeneration never writes workflow state.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { ADAPTER_ARTIFACTS, ADAPTER_REGISTRY } from "./registry.js";
import { renderAdapterFiles } from "./generate.js";
import type { AdapterSource } from "./types.js";

export const LETRA_GENERATED_HEADER = /^#\s*(Generated by letra|Gerado por letra)\b/i;

export type AdapterFileAction = "create" | "update" | "unchanged" | "conflict";

export interface AdapterFileResult {
	path: string;
	artifactId: string;
	action: AdapterFileAction;
}

export interface LocationRegeneration {
	location: string;
	files: AdapterFileResult[];
}

function isLetraGenerated(path: string): boolean {
	try {
		const firstLine = readFileSync(path, "utf8").split(/\r?\n/, 1)[0] ?? "";
		return LETRA_GENERATED_HEADER.test(firstLine);
	} catch {
		return false;
	}
}

type InstructionArtifactId = {
	[K in keyof typeof ADAPTER_ARTIFACTS]: (typeof ADAPTER_ARTIFACTS)[K]["kind"] extends "instructions" ? K : never;
}[keyof typeof ADAPTER_ARTIFACTS];

const INSTRUCTION_ARTIFACTS = Object.values(ADAPTER_ARTIFACTS).filter(
	(artifact): artifact is (typeof ADAPTER_ARTIFACTS)[InstructionArtifactId] => artifact.kind === "instructions",
);

/** Instruction artifacts present in the location that Letra generated. */
export function detectGeneratedArtifacts(locationPath: string): string[] {
	return INSTRUCTION_ARTIFACTS.filter((artifact) => {
		const path = join(locationPath, artifact.path);
		return existsSync(path) && isLetraGenerated(path);
	}).map((artifact) => artifact.id);
}

export function regenerateLocationAdapters(
	locationPath: string,
	options: { tools?: string[]; contentRoot?: string; dryRun?: boolean; source?: AdapterSource } = {},
): LocationRegeneration {
	const configured = (options.tools ?? []).filter((tool) => tool in ADAPTER_REGISTRY);
	const detected = new Set(detectGeneratedArtifacts(locationPath));
	const configuredArtifacts = new Set<string>(
		configured.flatMap((tool) => [...ADAPTER_REGISTRY[tool as keyof typeof ADAPTER_REGISTRY].artifactIds]),
	);
	// Render with the consumers of detected files too, so their content is the
	// one their tools expect (e.g. AGENTS.md with the Codex live-context note).
	const renderTools = new Set(configured);
	for (const id of detected) {
		for (const consumer of ADAPTER_ARTIFACTS[id as keyof typeof ADAPTER_ARTIFACTS].consumers) renderTools.add(consumer);
	}
	if (renderTools.size === 0) return { location: locationPath, files: [] };
	const rendered = renderAdapterFiles(locationPath, [...renderTools], {
		source: options.source ?? "sync",
		quiet: true,
		contentRoot: options.contentRoot,
	}).filter((file) => configuredArtifacts.has(file.artifactId) || detected.has(file.artifactId));

	const files: AdapterFileResult[] = [];
	for (const file of rendered) {
		const target = join(locationPath, file.path);
		const artifact = ADAPTER_ARTIFACTS[file.artifactId as keyof typeof ADAPTER_ARTIFACTS];
		const exists = existsSync(target);
		if (exists && artifact.kind === "instructions" && !isLetraGenerated(target)) {
			files.push({ path: target, artifactId: file.artifactId, action: "conflict" });
			continue;
		}
		if (exists && readFileSync(target, "utf8") === file.content) {
			files.push({ path: target, artifactId: file.artifactId, action: "unchanged" });
			continue;
		}
		files.push({ path: target, artifactId: file.artifactId, action: exists ? "update" : "create" });
		if (!options.dryRun) {
			mkdirSync(dirname(target), { recursive: true });
			writeFileSync(target, file.content, "utf8");
		}
	}
	return { location: locationPath, files };
}
