import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { syncMirror, syncNow } from "../commands/sync.js";
import { clearWorkspaceCache } from "../workspace/resolver.js";
import { detectGeneratedArtifacts, regenerateLocationAdapters } from "./regenerate.js";

const roots: string[] = [];
function tempDir(prefix: string): string {
	const dir = mkdtempSync(join(tmpdir(), prefix));
	roots.push(dir);
	return dir;
}
afterEach(() => {
	for (const dir of roots.splice(0)) rmSync(dir, { recursive: true, force: true });
	clearWorkspaceCache();
});

// What the repository's AGENTS.md looked like: a session snapshot of another
// workspace, generated by an older flow move.
const STALE_SESSION = "# Gerado por letra flow move. Nao edite manualmente.\n# Letra Session — Letra\n\nItem: ITEM-23 · Fase 1\nEstágio: Review → Security\nPapel: reviewer\n";

function expectBootstrap(content: string) {
	expect(content).toContain("# Letra Agent Bootstrap");
	expect(content).toContain("letra direction --item <ITEM-ID> --json");
	expect(content).not.toMatch(/ITEM-\d+/);
	expect(content).not.toContain("Letra Session");
	expect(content).not.toMatch(/Estágio:|Papel:/);
}

describe("adapter regeneration (ITEM-19/27)", () => {
	it("AC1/AC5: regenerates a Letra-generated file even with no configured tool", () => {
		const location = tempDir("letra-regen-location-");
		writeFileSync(join(location, "AGENTS.md"), STALE_SESSION);
		expect(detectGeneratedArtifacts(location)).toEqual(["agents-md-shared"]);

		const result = regenerateLocationAdapters(location, { tools: [] });

		expect(result.files).toEqual([expect.objectContaining({ artifactId: "agents-md-shared", action: "update" })]);
		expectBootstrap(readFileSync(join(location, "AGENTS.md"), "utf8"));
		// Only the detected file: no new files for the detected file's tools.
		expect(existsSync(join(location, ".codex"))).toBe(false);
		expect(existsSync(join(location, ".opencode"))).toBe(false);
	});

	it("AC4: never overwrites a human-authored instruction file", () => {
		const location = tempDir("letra-regen-human-");
		writeFileSync(join(location, "CLAUDE.md"), "# Team rules\n\nWritten by people.\n");

		const result = regenerateLocationAdapters(location, { tools: ["claude-code"] });

		expect(result.files).toEqual([expect.objectContaining({ artifactId: "claude-instructions", action: "conflict" })]);
		expect(readFileSync(join(location, "CLAUDE.md"), "utf8")).toBe("# Team rules\n\nWritten by people.\n");
	});

	it("creates configured tools' files and leaves an empty location alone", () => {
		const empty = tempDir("letra-regen-empty-");
		expect(regenerateLocationAdapters(empty, { tools: [] }).files).toEqual([]);

		const location = tempDir("letra-regen-tools-");
		const result = regenerateLocationAdapters(location, { tools: ["claude-code"] });
		expect(result.files).toEqual([expect.objectContaining({ artifactId: "claude-instructions", action: "create" })]);
		expectBootstrap(readFileSync(join(location, "CLAUDE.md"), "utf8"));
		expect(regenerateLocationAdapters(location, { tools: ["claude-code"] }).files[0]?.action).toBe("unchanged");
	});

	it("AC3: linking a project to a workspace regenerates its instruction files", () => {
		const workspace = tempDir("letra-regen-workspace-");
		writeFileSync(join(workspace, "workflow.json"), JSON.stringify({ version: "1.0", name: "Linked", createdAt: "2026-01-01T00:00:00.000Z", updatedAt: "2026-01-01T00:00:00.000Z", stages: [{ id: "code", name: "Code", order: 0 }], items: [], tools: [] }));
		const project = tempDir("letra-regen-project-");
		writeFileSync(join(project, ".letra-link"), `${workspace}\n`);
		writeFileSync(join(project, "AGENTS.md"), STALE_SESSION);

		const result = syncMirror(project, { direction: "link-to-workspace" });

		expect(result.ok).toBe(true);
		expect(result.filesUpdated).toContain(join(project, "AGENTS.md"));
		expectBootstrap(readFileSync(join(project, "AGENTS.md"), "utf8"));
	});

	it("AC2: letra sync regenerates the location without writing workflow state, and dry-run is faithful", async () => {
		const root = tempDir("letra-regen-sync-");
		const workflowPath = join(root, "workflow.json");
		writeFileSync(workflowPath, JSON.stringify({ version: "1.0", name: "Sync", createdAt: "2026-01-01T00:00:00.000Z", updatedAt: "2026-01-01T00:00:00.000Z", stages: [{ id: "code", name: "Code", order: 0 }], items: [], tools: [] }));
		mkdirSync(join(root, ".github"), { recursive: true });
		writeFileSync(join(root, "AGENTS.md"), STALE_SESSION);
		writeFileSync(join(root, ".github", "copilot-instructions.md"), "# Generated by letra init. Do not edit manually.\n# Letra Context — VSCode Copilot Adapter\n");
		const workflowBefore = readFileSync(workflowPath, "utf8");
		const workflowMtime = statSync(workflowPath).mtimeMs;

		const dryRun = await syncNow(root, { dryRun: true });
		expect(dryRun.ok).toBe(true);
		expect(dryRun.filesUpdated.sort()).toEqual([join(root, ".github", "copilot-instructions.md"), join(root, "AGENTS.md")].sort());
		expect(readFileSync(join(root, "AGENTS.md"), "utf8")).toBe(STALE_SESSION);

		const synced = await syncNow(root);
		expect(synced.filesUpdated.sort()).toEqual(dryRun.filesUpdated.sort());
		expectBootstrap(readFileSync(join(root, "AGENTS.md"), "utf8"));
		expectBootstrap(readFileSync(join(root, ".github", "copilot-instructions.md"), "utf8"));
		expect(readFileSync(workflowPath, "utf8")).toBe(workflowBefore);
		expect(statSync(workflowPath).mtimeMs).toBe(workflowMtime);
		expect(synced.filesUpdated.some((path) => path.includes(".letra/workflow.json"))).toBe(false);
	});
});
